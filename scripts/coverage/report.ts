// Writes coverage/REPORT.md from the checked-in inventories and classifications.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { check, counts, type CheckResult } from "./check.ts";
import {
  COVERAGE_DIR,
  SOURCES,
  SOURCE_TITLES,
  THEMES,
  readClassification,
  readInventory,
  type Classification,
  type Theme,
} from "./lib.ts";

const pct = (n: number) => `${n.toFixed(0)}%`;
const code = (s: string) => "`" + s.replace(/`/g, "'") + "`";

export function buildReport(): { markdown: string; problems: CheckResult[] } {
  const out: string[] = [];
  const problems: CheckResult[] = [];
  const gaps = new Map<Theme, string[]>();
  const sections: string[] = [];

  out.push("# Protocol coverage", "");
  out.push(
    "How much of each coding agent's native protocol, and of ACP, casm's protocol and providers cover.",
    "Generated by `npm run coverage` from `coverage/inventory/*.json` (extracted from each agent's own",
    "source of truth) and the hand-written classifications in `coverage/<source>.json`.",
    "",
    "- **mapped**: the provider translates it into a casm protocol element (for ACP: casm has an equivalent concept).",
    "- **ignored**: deliberately out of scope, with a reason.",
    "- **gap**: not handled yet.",
    "- **Mapped %** = mapped / (total - ignored).",
    "",
  );

  const rows: string[] = ["| Source | Version | Ids | Mapped | Ignored | Gap | Unclassified | Mapped % |", "|---|---|--:|--:|--:|--:|--:|--:|"];
  for (const source of SOURCES) {
    const inv = readInventory(source);
    const cls = readClassification(source);
    if (!inv) {
      rows.push(`| ${SOURCE_TITLES[source]} | (no inventory) | | | | | | |`);
      continue;
    }
    const r = check(inv, cls);
    if (r.unclassified.length || r.stale.length || r.invalid.length) problems.push(r);
    const c = counts(inv, cls);
    rows.push(`| ${SOURCE_TITLES[source]} | ${inv.version} | ${c.total} | ${c.mapped} | ${c.ignored} | ${c.gap} | ${c.unclassified} | ${pct(c.pct)} |`);

    // Per-source table, by kind.
    const byKind = new Map<string, { mapped: number; ignored: number; gap: number; unclassified: number }>();
    for (const item of inv.items) {
      const k = byKind.get(item.kind) ?? { mapped: 0, ignored: 0, gap: 0, unclassified: 0 };
      const s = cls?.items[item.id]?.status;
      if (s === "mapped" || s === "ignored" || s === "gap") k[s]++;
      else k.unclassified++;
      byKind.set(item.kind, k);
    }
    sections.push(`### ${SOURCE_TITLES[source]}`, "", `${inv.version}, from ${inv.from}.${cls?.description ? " " + cls.description : ""}`, "");
    sections.push("| Kind | Mapped | Ignored | Gap | Unclassified | Mapped % |", "|---|--:|--:|--:|--:|--:|");
    for (const [kind, k] of [...byKind].sort()) {
      const denom = k.mapped + k.gap + k.unclassified;
      sections.push(`| ${kind} | ${k.mapped} | ${k.ignored} | ${k.gap} | ${k.unclassified} | ${denom ? pct((100 * k.mapped) / denom) : "-"} |`);
    }
    sections.push(`| **total** | **${c.mapped}** | **${c.ignored}** | **${c.gap}** | **${c.unclassified}** | **${pct(c.pct)}** |`, "");

    for (const item of inv.items) {
      const cl = cls?.items[item.id] as Classification | undefined;
      if (cl?.status !== "gap") continue;
      const list = gaps.get(cl.theme) ?? [];
      list.push(`- **${source}** ${code(item.id)}: ${cl.note}`);
      gaps.set(cl.theme, list);
    }
  }

  out.push("## Summary", "", ...rows, "");
  if (problems.length) {
    out.push("## Problems", "");
    for (const p of problems) {
      if (p.unclassified.length) out.push(`- **${p.source}**: ${p.unclassified.length} unclassified: ${p.unclassified.map(code).join(", ")}`);
      if (p.stale.length) out.push(`- **${p.source}**: ${p.stale.length} classified but no longer in the inventory: ${p.stale.map(code).join(", ")}`);
      for (const e of p.invalid) out.push(`- **${p.source}**: ${e}`);
    }
    out.push("");
  }

  out.push("## Gaps by theme", "");
  const counted = [...gaps].sort((a, b) => b[1].length - a[1].length);
  out.push("| Theme | Gaps |", "|---|--:|", ...counted.map(([t, l]) => `| ${THEMES[t]} | ${l.length} |`), "");
  for (const [theme, list] of counted) out.push(`### ${THEMES[theme]}`, "", ...list, "");

  out.push("## Per source", "", ...sections);
  return { markdown: out.join("\n").replace(/\n+$/, "\n"), problems };
}

export function writeReport() {
  const r = buildReport();
  writeFileSync(join(COVERAGE_DIR, "REPORT.md"), r.markdown);
  return r;
}

if (import.meta.main) {
  const { problems } = writeReport();
  console.log("wrote coverage/REPORT.md");
  if (problems.length) process.exitCode = 1;
}
